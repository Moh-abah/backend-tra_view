# ============================================================== U7 ==========
# U7 · الخطة البديلة: الحدث قبل تأكد الساق → تسليح → دخول عند أول شمعة
#      تحقق الانطلاقة خلال liq_arm_bars (FIFO)
# الحدث@8 (الساق غير مؤكدة — القمة تؤكد عند 9): نافذة [3..7] مرجعها الشمعة 3
# (30 حمراء h=99.5) → اختراق 106.5>99.5 · حجم 35>30 → S1 مسلَّح عند 8
# الشمعة 9: قاعها 100.5 تحت خط الانطلاقة 101.084 → لا دخول بعد
# الشمعة 10: قاعها 104.9 ≥ 101.084 والساق مؤكدة الآن → الدخول البديل@10
FALLBACK_BASE = [
    C(1,  105,  105.5, 104.5, 105,   10),   # 0
    C(2,  105,  103.5, 102.5, 103,   12),   # 1
    C(3,  103,  101.5, 100.5, 101,   14),   # 2
    C(4,  101,   99.5,  96.5,  97,   30),   # 3 قاع (96.5) يؤكد عند 5
    C(5,   97,   98.5,  96.8,  98,   10),   # 4
    C(6,   98,  100.5,  97.5, 100,   26),   # 5 أخضر (26 > 25 يمنع مرجعاً في [1..5]/[2..6] — لا أحداث شاردة@6/7)
    C(7,  100,  101.2,  99.5, 101,   12),   # 6
    C(8,  101,  108.5, 100.8, 108,   25),   # 7 قمة (108.5) تؤكد عند 9
    C(9,  105,  106.5, 104.8, 106,   35),   # 8 الحدث S1 (ساق غير مؤكدة → تسليح)
    C(10, 105,  105.8, 100.5, 105.2, 12),   # 9 الساق تأكدت لكن القاع تحت الخط
    C(11, 105,  105.8, 104.9, 105.2, 12),   # 10 أول شمعة انطلاقة → دخول بديل
]
r7 = run(FALLBACK_BASE)
s7 = r7["series"]
assert s7["zzf_signal_s1"][8] == 1.0, "الحدث S1@8 (قبل تأكد الساق)"
assert s7["zzf_entry_s1"][8] == 0.0, "لا دخول بنفس شمعة الحدث — الساق غير مؤكدة"
assert s7["zzf_entry_s1"][10] == 1.0 and s7["zzf_entry"][10] == 1.0, "الدخول البديل عند أول شمعة انطلاقة"
assert s7["zzf_entry_s1"][9] == 0.0, "الشمعة 9 قاعها تحت الخط → لا دخول"
assert r7["liquidity"]["entries_fallback"] == 1 and r7["liquidity"]["entries_same_candle"] == 0
fb = [x for x in r7["signals"] if x["signal"] == "ZLF Entry S1"][0]
assert fb["fallback"] is True and fb["bar"] == 10
print("PASS-U7 · الخطة البديلة: حدث@8 مسلَّح → دخول@10 أول شمعة انطلاقة (fallback=True) ✓")

# ============================================================== U8 / U9b ====
# U8 · انتهاء صلاحية التسليح: liq_arm_bars=1 → التسليح يموت عند 9 والشمعة 10
