assert s2["zzf_signal_s1"][9] == 0.0 and s2["zzf_signal_s3"][9] == 0.0
assert s2["zzf_entry_s2"][9] == 1.0 and s2["zzf_entry"][9] == 1.0
assert r2["liquidity"]["entries_same_candle"] == 1
print("PASS-U2 · S2 = اختراق بحجم أقل (الإغلاق لا علاقة له بالتقسيم) + دخول بنفس الشمعة")

