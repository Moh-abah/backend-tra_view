# ============================================================== U5 ==========
# U5 · التمهيد + السبية: لا مرجع قبل اكتمال النافذة · الشمعة الكبيرة ليست
#      مرجعاً لنفسها (النافذة [i−K, i−1] لا تشمل i)
r5 = run(BASE_UP + [C(10, 105, 106.5, 104.8, 105.2, 45)])
s5 = r5["series"]
for warm in range(5):
    assert s5["zzf_liq_state"][warm] == 0.0, f"تمهيد: الشمعة {warm} بلا مرجع"
    assert s5["zzf_liq_ref_high"][warm] is None and s5["zzf_liq_ref_vol"][warm] is None
# عند الشمعة 8 (حمراء كبيرة vol=40): النافذة [3..7] → أكبر حجم 30 عند الشمعة 3
# السبية في حالة مصغّرة نقية: X3 (حمراء v=60) ليست مرجع نفسها عند شمعتها
# — النافذة [i−2, i−1] عند i=3 = {X1, X2} → المرجع X1 (50) لا X3 (60)
mini = [
    C(1, 100.5, 101.0,  99.5, 100,   10),   # X0 حمراء v=10 h=101
    C(2, 101.5, 101.5, 100.0, 100.5, 50),   # X1 حمراء v=50 h=101.5
    C(3, 102,   102.5,  99.5, 100.2, 20),   # X2 حمراء v=20 h=102.5
    C(4, 103,   103.5, 100.8, 101,   60),   # X3 حمراء v=60 h=103.5
    C(5, 101,   101.5, 100.2, 100.8, 30),   # X4 حمراء v=30
]
r5m = zigzag_fib(mini, length=2, liq_lookback=2, liq_signals=True)
s5m = r5m["series"]
assert s5m["zzf_liq_ref_vol"][2] == 50.0, "المرجع@2 = X1 (50)"
assert s5m["zzf_liq_ref_vol"][3] == 50.0, "السبية: مرجع@3 = X1 (50) — X3 (60) مستثناة من نافذتها"
assert s5m["zzf_liq_ref_vol"][4] == 60.0, "عند 4 تدخل X3 النافذة كمرجع سابق (60)"
assert s5m["zzf_liq_ref_high"][3] == 102.5  # أعلى قمة حمراء بالنافذة [1..2]
print("PASS-U5 · التمهيد + السبية: النافذة [i−K, i−1] حصرية والشمعة الكبيرة ليست مرجع نفسها")

# ============================================================== U6 / V5 =====
# U6 · V5: المرجع الأكبر حجمًا شمعة خضراء → لا مرجع (state 0) — لا إشارة إطلاقاً
# الشمعة 8 صارت خضراء بأكبر حجم بالنافذة [4..8] (41) → لا مرجع عند 9
V5_DATA = list(BASE_UP)
V5_DATA[8] = C(9, 105, 106.0, 104.0, 106, 41)   # خضراء (105→106) بأكبر حجم
