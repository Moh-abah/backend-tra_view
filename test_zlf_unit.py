# test_zlf_unit.py — اختبارات وحدة ZLF v13.2 (المصفوفة المصادقة من ثلاث جهات)
# =============================================================================
# U1–U10 : اختبارات الوحدة بدلالات v13.2 (إعادة تعريف الإشارات حسب نص الصور)
# V1–V8  : اختبارات القبول الإلزامية المصادقة (من رسالة وكيل الواجهة المعتمدة)
#
# المصفوفة المصادقة (v13.2):
#   R  = الشمعة صاحبة أكبر حجم في [i−K, i−1] بشرط أنها حمراء (close<open)
#        — أكبر شمعة خضراء → لا مرجع (state 0)
#   ref_high = أعلى high لشمعة حمراء داخل النافذة (محور الاختراق الموحد)
#   G  = خضراء (close>open) + الانطلاقة low ≥ price(0.382) لآخر ساق مؤكدة
#        (أي اتجاه) + هيمنة الخضراء (volume_G > كل الخضراء حصرياً بين R وG)
#   S1 = اختراق ∧ حجم أكبر · S2 = اختراق ∧ حجم أقل أو مساوٍ
#   S3 = رفض ∧ حجم أكبر · الرابعة (لا اختراق ∧ حجم أقل) = لا إشارة
#   الدخول = شمعة الحدث نفسها (المثالي) أو الخطة البديلة (تسليح liq_arm_bars)
#   SFP = إشارة رابعة اختيارية مطفأة افتراضياً (liq_sfp_signals=False)
# =============================================================================
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from app.services.indicators.overlays import zigzag_fib, ZZF_LAUNCH_LEVEL

def C(t, o, h, l, c, v):
    return {"timestamp": t, "open": o, "high": h, "low": l, "close": c, "volume": v}

def run(candles, **kw):
    base = dict(length=2, liq_lookback=5, liq_signals=True, liq_arm_bars=60)
    base.update(kw)
    return zigzag_fib(candles, **base)

# ---------------------------------------------------------------------------
# البيانات القاعدية (ساق صاعدة):
#   قاع زيجزاق عند الشمعة 3 (low=96.5) يؤكد عند 5 · قمة عند الشمعة 7 (high=108.5)
#   تؤكد عند 9 · الساق الصاعدة 96.5→108.5 · خط الانطلاقة price(0.382)
#   = 96.5 + 0.382×12 = 101.084
#   نافذة المرجع عند الشمعة 9 = [4..8]: أكبر حجم 40 عند الشمعة 8 (حمراء h=106)
#   → R = الشمعة 8 · ref_vol=40 · ref_high=106 (أعلى قمة حمراء بالنافذة)
# ---------------------------------------------------------------------------
BASE_UP = [
    C(1, 105.5, 105.5, 104.5, 105,   10),   # 0 أحمر
    C(2,  105,  103.5, 102.5, 103,   12),   # 1 أحمر
    C(3,  103,  101.5, 100.5, 101,   14),   # 2 أحمر
    C(4,  101,   99.5,  96.5,  97,   30),   # 3 أحمر — قاع الزيجزاق (96.5) · vol=30
    C(5,   97,   98.5,  96.8,  98,   35),   # 4 أخضر (أكبر حجم بالنوافذ [0..4]..[3..7] → لا مرجع فيها)
    C(6,   98,  100.5,  97.5, 100,   31),   # 5 أخضر
    C(7,  100,  101.2,  99.5, 101,   12),   # 6 أخضر
    C(8,  101,  108.5, 100.8, 108,   25),   # 7 أخضر — قمة الزيجزاق (108.5) تؤكد عند 9
    C(9, 105.5,  106.0, 104.0, 105,   40),  # 8 أحمر R: أكبر حجم بالنافذة (40) · h=106
]
LAUNCH_LINE = 96.5 + 0.382 * (108.5 - 96.5)   # = 101.084
assert abs(LAUNCH_LINE - 101.084) < 1e-9

# ============================================================== U1 / V6 =====
# U1 · S1 بالحالة المثالية: الحدث = الدخول بنفس شمعة الإشارة (V6)
# G@9: خضراء · اختراق 106.5>106 · حجم 45>40 · لا خضراء بينها وبين R (متجاورتان)
# · الانطلاقة low=104.8 ≥ 101.084 → S1 + دخول فوري بنفس الشمعة
ev = BASE_UP + [C(10, 105, 106.5, 104.8, 105.2, 45)]
r = run(ev)
s = r["series"]
assert s["zzf_liq_state"][9] == 1.0, f"state expected 1.0 got {s['zzf_liq_state'][9]}"
assert s["zzf_signal_s1"][9] == 1.0 and s["zzf_signal_any"][9] == 1.0
assert s["zzf_signal_s2"][9] == 0.0 and s["zzf_signal_s3"][9] == 0.0
assert s["zzf_entry_s1"][9] == 1.0, "الدخول الفوري بنفس شمعة الحدث (S1)"
assert s["zzf_entry"][9] == 1.0 and s["zzf_entry_s2"][9] == 0.0 and s["zzf_entry_s3"][9] == 0.0
assert s["zzf_liq_ref_high"][9] == 106.0, f"ref_high expected 106.0 got {s['zzf_liq_ref_high'][9]}"
assert s["zzf_liq_ref_vol"][9] == 40.0
assert s["zzf_liq_vol_ok"][9] == 1.0
assert r["liquidity"]["events"] == 1
assert r["liquidity"]["entries_same_candle"] == 1 and r["liquidity"]["entries_fallback"] == 0
assert r["liquidity"]["spec"] == "v13.2" and r["liquidity"]["launch_level"] == ZZF_LAUNCH_LEVEL
sig_names = [(x["bar"], x["signal"], x.get("fallback")) for x in r["signals"]]
assert "ZLF Liquidity S1" in [n for _b, n, _f in sig_names if _b == 9]
assert ("ZLF Entry S1", False) in [(n, f) for _b, n, f in sig_names if _b == 9]
ent_sig = [x for x in r["signals"] if x["signal"] == "ZLF Entry S1"][0]
assert abs(ent_sig["launch_line"] - LAUNCH_LINE) < 1e-9, f"launch_line {ent_sig['launch_line']} != {LAUNCH_LINE}"
print("PASS-U1 · S1 المثالي: الحدث = الدخول بنفس الشمعة · ref=106/40 · خط الانطلاقة 101.084 ✓")

# ============================================================== U2 / V1 =====
# U2 · S2 = اختراق بحجم أقل (V1 — يفشل عمداً على كود 13.1 حيث vol<ref يقتل الحدث)
# نفس شمعة U1 بحجم 30 ≤ 40 → S2 · والإغلاق 105.2 تحت القمة 106 — لا يؤثر إطلاقاً
# (التقسيم بعلاقة الحجم مع الحمراء لا بالإغلاق — الحرفية: «ويبرغم عندها لفل حجم»)
ev2 = BASE_UP + [C(10, 105, 106.5, 104.8, 105.2, 30)]
r2 = run(ev2)
s2 = r2["series"]
assert s2["zzf_liq_state"][9] == 2.0, f"S2 state expected 2.0 got {s2['zzf_liq_state'][9]}"
